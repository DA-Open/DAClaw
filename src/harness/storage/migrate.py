"""Run the harness migrations: ``python -m harness.storage.migrate``.

    python -m harness.storage.migrate upgrade            # to head
    python -m harness.storage.migrate downgrade base
    python -m harness.storage.migrate current
    python -m harness.storage.migrate heads
    python -m harness.storage.migrate revision -m "add x" --autogenerate

The database comes from ``DARAOS_HARNESS_DATABASE_DSN``. Autogenerated
scripts must be read before committing: Alembic does not see renames, and
partial indexes (like ``ix_tasks_queue``) must be checked by hand.
"""

from __future__ import annotations

import argparse
import asyncio
import os
import sys
from pathlib import Path

from alembic import command
from alembic.config import Config
from alembic.script import ScriptDirectory
from sqlalchemy.ext.asyncio import AsyncEngine, create_async_engine

from .postgres import async_url

MIGRATIONS = Path(__file__).with_name("migrations")


def alembic_config() -> Config:
    cfg = Config()
    cfg.set_main_option("script_location", str(MIGRATIONS))
    cfg.set_main_option("version_locations", str(MIGRATIONS / "versions"))
    cfg.set_main_option("path_separator", "os")
    return cfg


def heads() -> list[str]:
    return list(ScriptDirectory.from_config(alembic_config()).get_heads())


async def run(engine: AsyncEngine, action: str, *args: str, **kwargs) -> None:
    """Run an alembic command on a connection of ``engine``, in one transaction."""
    cfg = alembic_config()

    def _go(sync_conn) -> None:
        cfg.attributes["connection"] = sync_conn
        getattr(command, action)(cfg, *args, **kwargs)

    async with engine.begin() as conn:
        await conn.run_sync(_go)


async def upgrade(dsn: str, revision: str = "head") -> None:
    engine = create_async_engine(async_url(dsn))
    try:
        await run(engine, "upgrade", revision)
    finally:
        await engine.dispose()


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(prog="python -m harness.storage.migrate", description=__doc__.splitlines()[0])
    sub = parser.add_subparsers(dest="cmd", required=True)
    up = sub.add_parser("upgrade")
    up.add_argument("revision", nargs="?", default="head")
    down = sub.add_parser("downgrade")
    down.add_argument("revision")
    sub.add_parser("current")
    sub.add_parser("heads")
    rev = sub.add_parser("revision")
    rev.add_argument("-m", "--message", required=True)
    rev.add_argument("--autogenerate", action="store_true")
    args = parser.parse_args(argv)

    if args.cmd == "heads":
        print("\n".join(heads()))
        return 0
    dsn = os.environ.get("DARAOS_HARNESS_DATABASE_DSN")
    if not dsn:
        print("set DARAOS_HARNESS_DATABASE_DSN", file=sys.stderr)
        return 2

    async def go() -> None:
        engine = create_async_engine(async_url(dsn))
        try:
            if args.cmd == "upgrade":
                await run(engine, "upgrade", args.revision)
            elif args.cmd == "downgrade":
                await run(engine, "downgrade", args.revision)
            elif args.cmd == "current":
                await run(engine, "current", verbose=True)
            else:
                await run(engine, "revision", message=args.message, autogenerate=args.autogenerate)
        finally:
            await engine.dispose()

    asyncio.run(go())
    return 0


if __name__ == "__main__":
    sys.exit(main())
