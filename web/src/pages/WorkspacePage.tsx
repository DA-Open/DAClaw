function formatBytes(size: number): string {
  if (!Number.isFinite(size) || size <= 0) return "0 B";
  const units = ["B", "KB", "MB", "GB"];
  let value = size;
  let unit = 0;
  while (value >= 1024 && unit < units.length - 1) {
    value /= 1024;
    unit += 1;
  }
  const digits = unit === 0 || value >= 10 ? 0 : 1;
  return `${value.toFixed(digits)} ${units[unit]}`;
}

function formatTime(ts: number): string {
  if (!Number.isFinite(ts)) return "";
  return new Date(ts * 1000).toLocaleString(undefined, {
    month: "short",
    day: "numeric",
    hour: "2-digit",
    minute: "2-digit",
  });
}

function makeId(prefix: string): string {
  if (typeof crypto !== "undefined" && "randomUUID" in crypto) return `${prefix}-${crypto.randomUUID()}`;
  return `${prefix}-${Date.now()}-${Math.random().toString(16).slice(2)}`;
}

function truncateAssistantTraceText(value: string | undefined, limit = ASSISTANT_TRACE_TEXT_LIMIT): string | undefined {
  if (!value || value.length <= limit) return value;
  return `${value.slice(0, limit)}\n... [truncated ${value.length - limit} chars]`;
}

function sanitizeAssistantTraceEvent(event: ChatTraceEvent): ChatTraceEvent {
  let args = event.args;
  if (args && JSON.stringify(args).length > ASSISTANT_TRACE_TEXT_LIMIT) {
    args = { _truncated: truncateAssistantTraceText(JSON.stringify(args), ASSISTANT_TRACE_TEXT_LIMIT) };
  }
  return {
    ...event,
    message: truncateAssistantTraceText(event.message),
    text: truncateAssistantTraceText(event.text),
    preview: truncateAssistantTraceText(event.preview),
    result: truncateAssistantTraceText(event.result),
    args,
  };
}

function shouldKeepAssistantTraceEvent(event: ChatTraceEvent): boolean {
  if (event.type === "assistant_delta" || event.type === "reasoning" || event.type === "step" || event.type === "run_started") {
    return false;
  }
  if (event.type === "status") {
    return Boolean(event.is_error || /error|failed|exception|timeout/i.test(event.message || ""));
  }
  if (event.type === "tool_progress") {
    return Boolean(event.is_error);
  }
  return event.type === "tool_start" || event.type === "tool_complete" || event.type === "error";
}

function appendAssistantTraceEvent(trace: ChatTraceEvent[] = [], event: ChatTraceEvent): ChatTraceEvent[] {
  if (!shouldKeepAssistantTraceEvent(event)) return trace;
  return [...trace, sanitizeAssistantTraceEvent(event)].slice(-ASSISTANT_TRACE_EVENT_LIMIT);
}

function sanitizeAssistantTrace(trace: ChatTraceEvent[] = []): ChatTraceEvent[] {
  return trace.filter(shouldKeepAssistantTraceEvent).map(sanitizeAssistantTraceEvent).slice(-ASSISTANT_TRACE_EVENT_LIMIT);
}

