function createWorkspaceAssistantConversation(): WorkspaceAssistantConversation {
  return {
    id: makeId("workspace-chat"),
    title: "New conversation",
    updatedAt: Date.now(),
    sessionId: null,
    messages: [],
  };
}

function sanitizeAssistantMessages(messages: MiniMessage[] = []): MiniMessage[] {
  return messages
    .filter((message) => message && (message.role === "user" || message.role === "assistant") && typeof message.content === "string")
    .map((message) => ({ ...message, running: false, trace: sanitizeAssistantTrace(message.trace) }));
}

function sanitizeAssistantConversations(value: unknown): WorkspaceAssistantConversation[] {
  if (!Array.isArray(value)) return [];
  return value
    .filter((conversation) => conversation && typeof conversation === "object")
    .map((conversation) => {
      const item = conversation as Partial<WorkspaceAssistantConversation>;
      return {
        id: typeof item.id === "string" && item.id ? item.id : makeId("workspace-chat"),
        title: typeof item.title === "string" && item.title ? item.title : "Workspace analysis",
        updatedAt: typeof item.updatedAt === "number" ? item.updatedAt : Date.now(),
        sessionId: typeof item.sessionId === "string" ? item.sessionId : null,
        messages: sanitizeAssistantMessages(item.messages),
      };
    })
    .slice(0, 30);
}

function loadAssistantConversations(): WorkspaceAssistantConversation[] {
  try {
    const raw = window.localStorage.getItem(ASSISTANT_CONVERSATIONS_KEY);
    const conversations = sanitizeAssistantConversations(raw ? JSON.parse(raw) : []);
    if (conversations.length) return conversations;
  } catch {
    // Ignore corrupted local UI state.
  }

  try {
    const raw = window.localStorage.getItem(ASSISTANT_LEGACY_CONVERSATIONS_KEY);
    const conversations = sanitizeAssistantConversations(raw ? JSON.parse(raw) : []);
    if (conversations.length) return conversations;
  } catch {
    // Ignore corrupted local UI state.
  }

  try {
    const legacyRaw = window.localStorage.getItem(ASSISTANT_LEGACY_MEMORY_KEY);
    const legacyMessages = sanitizeAssistantMessages(legacyRaw ? (JSON.parse(legacyRaw) as MiniMessage[]) : []);
    if (legacyMessages.length) {
      return [
        {
          ...createWorkspaceAssistantConversation(),
          title: "Previous workspace chat",
          messages: legacyMessages,
        },
      ];
    }
  } catch {
    // Ignore corrupted legacy state.
  }

  return [createWorkspaceAssistantConversation()];
}

function persistableAssistantConversations(conversations: WorkspaceAssistantConversation[]): WorkspaceAssistantConversation[] {
  return conversations.slice(0, 30).map((conversation) => ({
    ...conversation,
    messages: sanitizeAssistantMessages(conversation.messages),
  }));
}

